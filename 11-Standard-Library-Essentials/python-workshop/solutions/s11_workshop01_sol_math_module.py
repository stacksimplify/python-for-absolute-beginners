"""
Workshop Problem-01: math module (Car Math) (solution)

Concepts: math.sqrt, math.ceil, math.floor.

Write a program that, using the math module, prints these labeled lines:
  Task-1: the square root of 196 (use math.sqrt).
  Task-2: the ceiling of 9.1 (use math.ceil).
  Task-3: the floor of 7.9 (use math.floor).

Expected output:
sqrt 196: 14.0
ceil 9.1: 10
floor 7.9: 7
"""
import math

# Task-1: print the square root of 196
print("sqrt 196:", math.sqrt(196))
# Task-2: print the ceiling of 9.1
print("ceil 9.1:", math.ceil(9.1))
# Task-3: print the floor of 7.9
print("floor 7.9:", math.floor(7.9))

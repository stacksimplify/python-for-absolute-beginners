"""
Practice Problem-02: comparison (solution)

Concepts: comparison operators (>, <, ==, >=); each answers True or False.

Problem-1: Stock Check.
Write a program that, for a stock of 72:
  Task-1: print whether stock is greater than 50.
  Task-2: print whether stock equals 72.
  Task-3: print whether stock is less than 40.
  Task-4: print whether stock is greater than or equal to 60.

Expected output:
True
True
False
True
"""

stock = 72
# Task-1: print whether stock is greater than 50
print(stock > 50)
# Task-2: print whether stock equals 72
print(stock == 72)
# Task-3: print whether stock is less than 40
print(stock < 40)
# Task-4: print whether stock is at least 60
print(stock >= 60)

"""
Problem-2: Coupon Applied?
  Write a program that, for a coupon whose value is None:
    Task-1: print whether coupon is None.
    Task-2: print whether coupon is not None.

Expected output:
True
False
"""
coupon = None
# Task-1: print whether coupon is None
print(coupon is None)
# Task-2: print whether coupon is not None
print(coupon is not None)

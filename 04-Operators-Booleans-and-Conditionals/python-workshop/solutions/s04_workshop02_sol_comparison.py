"""
Workshop Problem-02: comparison (Speed Check) (solution)

Concepts: comparison operators.

Write a program that, for a speed of 80 and a limit of 60:
  Task-1: print whether the speed is above the limit.
  Task-2: print whether the speed equals the limit.
  Task-3: print whether the speed is 100 or below.

Expected output:
True
False
True
"""

speed = 80
limit = 60
# Task-1: print whether the speed is above the limit
print(speed > limit)
# Task-2: print whether the speed equals the limit
print(speed == limit)
# Task-3: print whether the speed is 100 or below
print(speed <= 100)
